import { expect, test, type Page } from '@playwright/test'

async function createMember(page: Page) {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Welcome back.' })).toBeVisible()
  await page.getByRole('link', { name: /Create an account/ }).click()
  await page.getByLabel('First name').fill('Alex')
  await page.getByLabel('Last name').fill('Sample')
  await page.getByLabel('Date of birth').fill('2000-06-15')
  await page.getByLabel('Email address').fill('alex@example.com')
  await page.getByLabel('Phone number').fill('(512) 555-0123')
  await page.getByLabel('Street address').fill('123 Sample Street')
  await page.getByLabel('City').fill('San Marcos')
  await page.getByLabel('State').selectOption('TX')
  await page.getByLabel('ZIP code').fill('78666')
  await page.getByLabel('Identification type').selectOption('drivers-license')
  await page.getByLabel('Identification last four digits').fill('4821')
  await page.getByLabel('SSN last four digits').fill('0000')
  await page.getByLabel('Create password').fill('safe-password')
  await page.getByLabel('Confirm password').fill('safe-password')
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page.getByRole('heading', { name: /What are you looking for/ })).toBeVisible()
  await page.getByRole('button', { name: /Everyday banking/ }).click()
  await page.getByRole('button', { name: /Direct deposit/ }).click()
  await page.getByLabel('Employment or student status').selectOption('Student')
  await page.getByLabel('Minimum annual income ($)').fill('40000')
  await page.getByLabel('Maximum annual income ($)').fill('20000')
  await page.getByRole('button', { name: /Continue to my recommendation/ }).click()
  await expect(page.getByText(/Enter both amounts/)).toBeVisible()
  await page.getByLabel('Minimum annual income ($)').fill('0')
  await page.getByRole('button', { name: /Continue to my recommendation/ }).click()
  await page.getByRole('button', { name: 'Back to choices' }).click()
  await expect(page.getByLabel('Employment or student status')).toHaveValue('Student')
  await expect(page.getByLabel('Minimum annual income ($)')).toHaveValue('0')
  await expect(page.getByLabel('Maximum annual income ($)')).toHaveValue('20000')
  await page.getByRole('button', { name: /Continue to my recommendation/ }).click()
  await expect(page.getByRole('heading', { name: /clear starting point/ })).toBeVisible()
  await expect(page.locator('.card-design-option img')).toHaveCount(3)
  expect(await page.locator('.card-design-option img').evaluateAll(images => images.every(image => (image as HTMLImageElement).naturalWidth > 0))).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('radio', { name: /Texas State University/ }).check()
  await page.getByRole('button', { name: /Review my information/ }).click()
  await expect(page.getByText('Texas State University', { exact: true })).toBeVisible()
  await expect(page.getByText('Student', { exact: true })).toBeVisible()
  await expect(page.getByText('$0.00 – $20,000.00', { exact: true })).toBeVisible()
  await expect(page.getByText('•••• 0000')).toBeVisible()
  const consent = page.getByRole('checkbox')
  await consent.nth(0).check()
  await consent.nth(1).check()
  await page.getByRole('button', { name: /Continue to review/ }).click()
  await expect(page.getByRole('heading', { name: /Reviewing your UFCU setup/ })).toBeVisible()
  await expect(page.getByRole('heading', { name: /Congratulations, Alex/ })).toBeVisible({ timeout: 10000 })
  await page.getByRole('button', { name: /Continue with card setup/ }).click()
  await expect(page.getByRole('heading', { name: 'Cards & Wallet' })).toBeVisible()
  await expect(page.getByAltText('Your selected UFCU debit card design')).toHaveAttribute('src', '/images/cards/texas-state.png')
  await page.getByRole('button', { name: 'Activate card' }).click()
  await page.getByRole('button', { name: /Continue to dashboard/ }).click()
  await expect(page).toHaveURL(/\/dashboard$/)
}

