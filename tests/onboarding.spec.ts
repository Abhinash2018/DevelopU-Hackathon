test('ID image preview validates files and can be replaced or removed', async ({ page }) => {
  await page.goto('/signup')
  const upload = page.locator('#identity-image')
  await upload.setInputFiles({ name: 'invalid.txt', mimeType: 'text/plain', buffer: Buffer.from('invalid') })
  await expect(page.getByRole('alert')).toHaveText('Choose a JPG, PNG, or WebP image.')
  await upload.setInputFiles({ name: 'large.png', mimeType: 'image/png', buffer: Buffer.alloc(5 * 1024 * 1024 + 1) })
  await expect(page.getByRole('alert')).toHaveText('Choose an image smaller than 5 MB.')
  await upload.setInputFiles('public/images/cards/classic.png')
  await expect(page.getByAltText('Selected identification preview')).toBeVisible()
  await expect(page.getByRole('status')).toContainText('classic.png')
  await upload.setInputFiles('public/images/cards/texas.png')
  await expect(page.getByRole('status')).toContainText('texas.png')
  await page.getByRole('button', { name: 'Remove image' }).click()
  await expect(page.getByAltText('Selected identification preview')).toHaveCount(0)
})


test('sign-in opens the dashboard directly, including after sign-out', async ({ page }) => {
  await page.goto('/preferences')
  await expect(page.getByRole('heading', { name: 'Welcome back.' })).toBeVisible()
  for (let attempt = 0; attempt < 2; attempt++) {
    await page.getByLabel('Email or username').fill('member@example.com')
    await page.getByLabel('Password', { exact: true }).fill('demo-password')
    await page.getByRole('button', { name: 'Sign in', exact: true }).click()
    await expect(page).toHaveURL(/\/dashboard$/)
    await expect(page.getByRole('heading', { name: 'Good morning, Ayush.' })).toBeVisible()
    if (attempt === 0) await page.getByRole('button', { name: 'Sign out' }).click()
  }
})

test('merchant rows and map pins open their own offer details', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByLabel('Email or username').fill('member@example.com')
  await page.getByLabel('Password', { exact: true }).fill('demo-password')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.getByRole('main').getByRole('link', { name: 'Nearby Offers' }).click()
  await page.getByRole('button', { name: 'Allow once' }).click()
  for (const [merchant, headline] of [['H-E-B', '$5 back on groceries'], ['Target', '10% back on your next shop'], ['Local Coffee', '$2 off your coffee break']]) {
    const trigger = page.getByRole('button', { name: `View ${merchant} offer`, exact: true })
    await trigger.click()
    const dialog = page.getByRole('dialog', { name: `${merchant} offer` })
    await expect(dialog).toBeVisible()
    await expect(dialog.getByText(headline, { exact: true })).toBeVisible()
    await expect(dialog.getByText('Demo offer · Not redeemable')).toBeVisible()
    expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
    await page.keyboard.press('Escape')
    await expect(dialog).toHaveCount(0)
    await expect(trigger).toBeFocused()
    await page.getByRole('button', { name: `View ${merchant} offer on map`, exact: true }).click()
    await expect(dialog).toBeVisible()
    await dialog.getByRole('button', { name: 'Back to offers' }).click()
    await expect(dialog).toHaveCount(0)
  }
})
